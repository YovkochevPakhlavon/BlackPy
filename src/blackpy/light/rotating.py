r"""Shadows of rotating black holes with separable null geodesics.

Separability
------------
Let :math:`W = g_{\theta\theta}`. If, in the given coordinates,

.. math::

    W g^{tt} = T_r(r) + T_\theta(\theta), \quad
    W g^{t\phi} = P_r(r) + P_\theta(\theta), \quad
    W g^{\phi\phi} = Q_r(r) + Q_\theta(\theta), \quad
    W g^{rr} = \Delta_r(r),

the null Hamilton-Jacobi equation separates (derivation in
``docs/theory.md``, section 13). The split is fixed by
:math:`T_\theta(\pi/2) = P_\theta(\pi/2) = Q_\theta(\pi/2) = 0`. With
:math:`\xi = L/E` and the Carter-like constant :math:`\eta = \mathcal{K}/E^2`,

.. math::

    \Delta_r\,p_r^2/E^2 = \mathcal{R}(r) \equiv -T_r + 2P_r\xi - Q_r\xi^2 - \eta,
    \qquad
    p_\theta^2/E^2 = \Theta(\theta) \equiv \eta - T_\theta + 2P_\theta\xi - Q_\theta\xi^2 .

For Kerr this is the usual
:math:`\mathcal{R} = [(r^2 + a^2 - a\xi)^2 - \Delta((\xi - a)^2 + \eta)]/\Delta`
and :math:`\Theta = \eta + a^2\cos^2\theta - \xi^2\cot^2\theta`. The class
covers Kerr, Kerr-Newman, the Johannsen metric and all metrics generated by
:func:`blackpy.metric.rotating_from_static`. Metrics that fail the test are
refused: they need numerical ray tracing, which BlackPy does not provide (an
external option is Gradus.jl).

Spherical photon orbits
-----------------------
:math:`\mathcal{R} = \mathcal{R}' = 0` at radius :math:`r_p` gives

.. math::

    \xi(r_p) = \frac{T_r'}{P_r' + {\rm sgn}(P_r')\sqrt{P_r'^2 - Q_r'T_r'}}, \qquad
    \eta(r_p) = -T_r + 2P_r\xi - Q_r\xi^2 ,

the root of the quadratic :math:`Q_r'\xi^2 - 2P_r'\xi + T_r' = 0` of smaller
magnitude (the other root, :math:`\xi = (r^2 + a^2)/a` in Kerr, has
:math:`\Theta < 0` everywhere). These are the critical impact parameters.

Shadow
------
For an observer at infinity at inclination :math:`i` (Bardeen 1973; as
reproduced by Perlick & Tsupko 2022, Phys. Rep. 947, 1, Eq. (55))

.. math::

    \alpha = -\frac{\xi}{\sin i}, \qquad \beta = \pm\sqrt{\Theta(i)} .

The contour is traced by :math:`r_p` between the two roots of
:math:`\Theta(i) = 0`. For a zero-angular-momentum observer (ZAMO) at finite
radius :math:`r_O` and polar angle :math:`i`, the photon's direction cosines
in the observer's orthonormal frame are used; see :func:`shadow_contour`.

Shape observables are defined in :func:`shadow_observables`.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import NamedTuple

import jax
import jax.numpy as jnp
import numpy as np

from blackpy._numerics import find_roots, nanmax_or_nan, value_and_derivative
from blackpy.errors import NotAsymptoticallyFlatError, NotSeparableError
from blackpy.geometry.horizons import static_domain_core
from blackpy.metric.axisymmetric import separable_functions

HALF_PI = 0.5 * math.pi

#: Inclinations are clamped to [MIN_INCLINATION, pi - MIN_INCLINATION] (radians).
MIN_INCLINATION = 1e-4

_EDGE = 1e-9

#: Frame dragging below this (dimensionless) size is neglected altogether.
_NEGLIGIBLE = 1e-5

#: Below this size the shape observables are those of the non-rotating circle.
_SLOW = 2e-4


def require_separable(metric) -> None:
    """Raise :class:`blackpy.errors.NotSeparableError` unless null geodesics separate."""
    if not metric.is_separable:
        raise NotSeparableError(
            f"The null geodesics of metric '{metric.name}' do not separate in these "
            "coordinates (W g^tt, W g^tphi, W g^phiphi are not sums of a function of r and a "
            "function of theta, or W g^rr depends on theta; W = g_thetatheta). The shadow of "
            "such a metric needs numerical ray tracing, which is outside the scope of BlackPy; "
            "an external option is Gradus.jl. To test specific parameter values use "
            "metric.check_separability(**params)."
        )


def _as_rotating(metric):
    """Static metrics are handled through their axisymmetric form (a circle results)."""
    return metric if metric.is_rotating_class else metric.as_axisymmetric()


# ----------------------------------------------------------------------------- building blocks


def _radial_parts(metric, p, r):
    t, pp, q, _ = separable_functions(metric, p, r, HALF_PI)
    return jnp.stack([t, pp, q])


def critical_core(metric, p, r_p):
    """Critical impact parameters ``(xi, eta)`` of the spherical photon orbit at ``r_p``."""
    (t, pp, q), (t1, p1, q1) = value_and_derivative(lambda x: _radial_parts(metric, p, x), r_p)
    disc = p1**2 - q1 * t1
    ok = disc >= 0.0
    root = jnp.sqrt(jnp.where(ok, disc, 0.0))
    denom = p1 + jnp.where(p1 >= 0.0, 1.0, -1.0) * root
    ok = ok & (denom != 0.0)
    xi = jnp.where(ok, t1 / jnp.where(ok, denom, 1.0), jnp.nan)
    return xi, -t + 2.0 * pp * xi - q * xi**2


def _polar_parts(metric, p, theta, r_ref):
    """``(T_theta, P_theta, Q_theta)`` at polar angle ``theta``."""
    at = separable_functions(metric, p, r_ref, theta)
    eq = separable_functions(metric, p, r_ref, HALF_PI)
    return at[0] - eq[0], at[1] - eq[1], at[2] - eq[2]


def _theta_potential(xi, eta, polar):
    t_th, p_th, q_th = polar
    return eta - t_th + 2.0 * p_th * xi - q_th * xi**2


class _Setup(NamedTuple):
    inclination: jax.Array
    polar: tuple
    r_lo: jax.Array
    r_hi: jax.Array
    rotating: jax.Array
    slow: jax.Array
    circle_radius: jax.Array
    r_sphere: jax.Array
    r_in: jax.Array
    r_cosmo: jax.Array


def _setup(metric, p, inclination, n_scan) -> _Setup:
    """Photon region for this inclination, plus the non-rotating fallback.

    The search is anchored at the spherical photon orbit with ``xi = 0`` (the polar
    orbit), ``T_r' = 0``: it exists for every spin and always lies inside the photon
    region. The two ends of the region are the roots of ``Theta(i) = 0`` nearest to it
    on either side. (Searching for "the outermost roots" instead fails at small spin,
    where round-off noise in ``Q_r'`` at large radii produces spurious roots.)
    """
    inclination = jnp.clip(inclination, MIN_INCLINATION, math.pi - MIN_INCLINATION)
    r_event, r_cosmo, r_in, r_out = static_domain_core(metric, p, n_scan=n_scan)
    lo, hi = r_in * (1.0 + _EDGE), r_out * (1.0 - _EDGE)

    def t_prime(r):
        return value_and_derivative(lambda x: _radial_parts(metric, p, x)[0], r)[1]

    # Unstable polar orbit: T_r has a maximum (T_r' decreases through zero); outermost one.
    spheres, _ = find_roots(t_prime, lo, hi, n_scan=n_scan, max_roots=3, detect_extrema=False)
    safe = jnp.where(jnp.isfinite(spheres), spheres, 3.0)
    decreasing = jax.vmap(lambda x: value_and_derivative(t_prime, x)[1])(safe) < 0.0
    r_s = nanmax_or_nan(spheres, decreasing)
    found = jnp.isfinite(r_s)
    safe_s = jnp.where(found, r_s, 3.0)
    parts, slopes = value_and_derivative(lambda x: _radial_parts(metric, p, x), safe_s)
    # Dimensionless size of the frame-dragging term P_r' at r_s (18 a for Kerr).
    # Below _NEGLIGIBLE (a < 5.6e-7 in Kerr) the metric is treated as non-rotating: a
    # centred circle; the neglected shift of the contour, 2 a sin(i), is below 1.2e-6 M.
    # Below _SLOW (a < 1.1e-5) the contour is still traced, but the shape integrals use
    # a displaced circle, because derivatives along a contour whose width in r_p is ~a
    # are dominated by round-off; the neglected terms are O(a^2) < 2e-10.
    dragging = jnp.abs(slopes[1]) * safe_s**2
    negligible = (dragging < _NEGLIGIBLE) & (jnp.abs(slopes[2]) * safe_s < _NEGLIGIBLE)
    slow = dragging < _SLOW

    polar = _polar_parts(metric, p, inclination, 3.0 * safe_s)

    def potential(r):
        return _theta_potential(*critical_core(metric, p, r), polar)

    below, _ = find_roots(potential, lo, safe_s, n_scan=n_scan, max_roots=2, detect_extrema=False)
    above, _ = find_roots(
        potential,
        safe_s,
        jnp.minimum(hi, 50.0 * safe_s),
        n_scan=n_scan,
        max_roots=6,
        detect_extrema=False,
    )
    r_lo = nanmax_or_nan(below, jnp.isfinite(below))
    r_hi = -nanmax_or_nan(-above, jnp.isfinite(above))
    rotating = found & (~negligible) & jnp.isfinite(r_lo) & jnp.isfinite(r_hi)
    ok = found & (negligible | slow) & (parts[0] < 0.0)
    radius = jnp.where(ok, jnp.sqrt(jnp.where(ok, -parts[0], 1.0)), jnp.nan)
    return _Setup(inclination, polar, r_lo, r_hi, rotating, slow, radius, r_s, r_in, r_cosmo)


def _screen_map(metric, p, setup: _Setup, r_obs, finite: bool):
    """Function ``(xi, eta) -> (alpha, beta^2)`` and whether the observer is admissible."""
    inc = setup.inclination
    if not finite:
        sin_i = jnp.sin(inc)
        return (lambda xi, eta: (-xi / sin_i, _theta_potential(xi, eta, setup.polar))), True
    g_tt, g_tphi, g_phiphi, _, g_thth = metric.components_array(r_obs, inc, p)
    lapse2 = -g_tt + g_tphi**2 / g_phiphi
    omega = -g_tphi / g_phiphi
    outer_edge = jnp.where(setup.rotating, setup.r_hi, setup.r_sphere)
    # The outer limit is the cosmological horizon, if any; the scan range does not
    # restrict the observer position.
    inside_cosmo = jnp.where(jnp.isfinite(setup.r_cosmo), r_obs < setup.r_cosmo, True)
    ok = (lapse2 > 0.0) & (g_phiphi > 0.0) & (r_obs > outer_edge) & inside_cosmo
    lapse = jnp.sqrt(jnp.where(ok, lapse2, 1.0))
    scale = jnp.sqrt(jnp.where(ok, g_thth / g_phiphi, 1.0))

    def to_screen(xi, eta):
        energy = (1.0 - omega * xi) / lapse  # locally measured energy per unit E
        return -scale * xi / energy, _theta_potential(xi, eta, setup.polar) / energy**2

    return to_screen, ok


def _upper_half(metric, p, setup: _Setup, to_screen, t):
    """``(alpha, beta)`` on the upper half of the contour at parameter ``t`` in [0, pi]."""
    mid, half = 0.5 * (setup.r_hi + setup.r_lo), 0.5 * (setup.r_hi - setup.r_lo)
    r_p = jnp.where(setup.rotating, mid - half * jnp.cos(t), 3.0)
    alpha, beta2 = to_screen(*critical_core(metric, p, r_p))
    beta = jnp.sqrt(jnp.clip(beta2, 0.0, None))
    return (
        jnp.where(setup.rotating, alpha, jnp.nan),
        jnp.where(setup.rotating, beta, jnp.nan),
        r_p,
    )


# ----------------------------------------------------------------------------- core functions


def photon_region_core(metric, p, inclination, n_scan=256):
    """Radii ``(r_min, r_max)`` of the spherical photon orbits that form the shadow rim."""
    setup = _setup(metric, p, inclination, n_scan)
    return (
        jnp.where(setup.rotating, setup.r_lo, jnp.nan),
        jnp.where(setup.rotating, setup.r_hi, jnp.nan),
    )


def _circle_radius_on_screen(metric, p, setup: _Setup, r_obs, finite: bool):
    """Radius of the non-rotating shadow on the observer's screen.

    At infinity it is the critical impact parameter ``b_c``. For a static observer at
    ``r_O`` it is ``b_c sqrt(-g_tt(r_O))``, i.e. ``sqrt(h) sin(alpha_sh)`` of Synge's formula.
    """
    if not finite:
        return setup.circle_radius
    g_tt = metric.gtt_array(r_obs, setup.inclination, p)
    return setup.circle_radius * jnp.sqrt(jnp.clip(-g_tt, 0.0, None))


def contour_core(metric, p, inclination, r_obs, n=256, n_scan=256, finite=False):
    """Closed shadow contour: arrays ``alpha``, ``beta`` (2n - 2 points) and ``r_p``.

    NaN if the shadow is undefined (no photon region, observer inside it).
    """
    setup = _setup(metric, p, inclination, n_scan)
    to_screen, ok = _screen_map(metric, p, setup, r_obs, finite)
    t = jnp.linspace(0.0, math.pi, n)
    alpha, beta, r_p = jax.vmap(lambda x: _upper_half(metric, p, setup, to_screen, x))(t)
    # Non-rotating case: circle of the photon-sphere impact parameter.
    radius = _circle_radius_on_screen(metric, p, setup, r_obs, finite)
    alpha = jnp.where(setup.rotating, alpha, -radius * jnp.cos(t))
    beta = jnp.where(setup.rotating, beta, radius * jnp.sin(t))
    alpha = jnp.where(ok, alpha, jnp.nan)
    beta = jnp.where(ok, beta, jnp.nan)
    return (
        jnp.concatenate([alpha, alpha[-2:0:-1]]),
        jnp.concatenate([beta, -beta[-2:0:-1]]),
        jnp.concatenate([r_p, r_p[-2:0:-1]]),
    )


class ShadowObservables(NamedTuple):
    """Shape and size of a shadow (see :func:`shadow_observables`)."""

    mean_radius: jax.Array
    area_radius: jax.Array
    delta_c: jax.Array
    centroid: jax.Array
    area: jax.Array
    alpha_min: jax.Array
    alpha_max: jax.Array
    beta_max: jax.Array


def observables_core(
    metric, p, inclination, r_obs, n=256, n_scan=256, finite=False
) -> ShadowObservables:
    """Shadow observables by midpoint quadrature along the contour (jit/vmap-compatible)."""
    setup = _setup(metric, p, inclination, n_scan)
    to_screen, ok = _screen_map(metric, p, setup, r_obs, finite)
    t = (jnp.arange(n) + 0.5) * (math.pi / n)
    weight = math.pi / n

    def point(x):
        alpha, beta, _ = _upper_half(metric, p, setup, to_screen, x)
        return jnp.stack([alpha, beta])

    values, slopes = jax.vmap(lambda x: value_and_derivative(point, x))(t)
    alpha, beta, d_alpha, d_beta = values[:, 0], values[:, 1], slopes[:, 0], slopes[:, 1]
    signed = jnp.sum(beta * d_alpha) * weight  # integral of beta d(alpha) over the upper half
    area = 2.0 * jnp.abs(signed)
    centroid = jnp.sum(alpha * beta * d_alpha) * weight / signed
    ell = jnp.sqrt((alpha - centroid) ** 2 + beta**2)
    d_phi = ((alpha - centroid) * d_beta - beta * d_alpha) / ell**2
    star_shaped = jnp.all(d_phi > 0.0) | jnp.all(d_phi < 0.0)
    area_radius = jnp.sqrt(area / math.pi)
    mean_radius = jnp.sum(ell * jnp.abs(d_phi)) * weight / math.pi
    variance = jnp.sum((ell - area_radius) ** 2 * jnp.abs(d_phi)) * weight / math.pi
    delta_c = jnp.sqrt(variance) / area_radius
    edges = jax.vmap(lambda x: _upper_half(metric, p, setup, to_screen, x)[0])(
        jnp.asarray([0.0, math.pi])
    )
    rotating = ShadowObservables(
        mean_radius=jnp.where(star_shaped, mean_radius, jnp.nan),
        area_radius=area_radius,
        delta_c=jnp.where(star_shaped, delta_c, jnp.nan),
        centroid=centroid,
        area=area,
        alpha_min=jnp.min(edges),
        alpha_max=jnp.max(edges),
        beta_max=jnp.max(beta),
    )
    radius = _circle_radius_on_screen(metric, p, setup, r_obs, finite)
    zero = jnp.zeros_like(radius)
    # Slowly rotating: a circle displaced to the midpoint of its horizontal extent.
    shift = jnp.where(setup.rotating, 0.5 * (edges[0] + edges[1]), 0.0)
    circle = ShadowObservables(
        radius, radius, zero, shift, math.pi * radius**2, shift - radius, shift + radius, radius
    )
    use_contour = setup.rotating & (~setup.slow)
    return ShadowObservables(
        *[
            jnp.where(ok, jnp.where(use_contour, a, b), jnp.nan)
            for a, b in zip(rotating, circle, strict=True)
        ]
    )


def mean_radius_core(metric, p, inclination, n=128, n_scan=256):
    """Mean shadow radius for an observer at infinity (used by the shadow likelihood)."""
    return observables_core(metric, p, inclination, jnp.inf, n=n, n_scan=n_scan).mean_radius


def area_radius_core(metric, p, inclination, n=128, n_scan=256):
    """Area-equivalent shadow radius for an observer at infinity."""
    return observables_core(metric, p, inclination, jnp.inf, n=n, n_scan=n_scan).area_radius


# ----------------------------------------------------------------------------- public API


class CriticalParameters(NamedTuple):
    """Critical impact parameters of a spherical photon orbit.

    Attributes
    ----------
    xi : ``L / E``, the axial angular momentum per unit energy (units of M)
    eta : ``K / E^2``, the Carter-like constant per unit energy squared (units of M^2)
    """

    xi: jax.Array
    eta: jax.Array


def critical_impact_parameters(metric, r_p, **params) -> CriticalParameters:
    r"""Critical impact parameters :math:`(\xi, \eta)` of the spherical photon orbit at ``r_p``.

    Photons with these constants of motion orbit at constant radius ``r_p``
    (unstably); they separate captured from scattered photons.

    Parameters
    ----------
    metric : StationaryAxisymmetric
        Must have separable null geodesics.
    r_p : float or array
        Radius of the spherical photon orbit in units of M.
    **params
        Metric parameters.

    Returns
    -------
    CriticalParameters
        For Kerr (Bardeen 1973): :math:`\xi = -[r^2(r - 3) + a^2(r + 1)] /
        [a(r - 1)]` and :math:`\eta = r^3[4a^2 - r(r - 3)^2] / [a^2(r - 1)^2]`.
        NaN where the metric has no rotation (``a = 0``), because every
        :math:`\xi` then belongs to the same radius; use
        :func:`shadow_contour`, which handles that case.

    Raises
    ------
    NotSeparableError
        If the null geodesics of the metric do not separate.
    """
    metric = _as_rotating(metric)
    require_separable(metric)
    return CriticalParameters(*metric.evaluate(critical_core, params, r_p))


def photon_region(metric, inclination=HALF_PI, *, n_scan: int = 256, **params):
    """Radial range of the spherical photon orbits that form the shadow rim.

    Parameters
    ----------
    metric : StationaryAxisymmetric
    inclination : float or array
        Polar angle of the observer in radians (default: edge-on, where the
        range is widest and its ends are the prograde and retrograde
        equatorial photon orbits).
    **params
        Metric parameters.

    Returns
    -------
    (jax.Array, jax.Array)
        ``(r_min, r_max)`` in units of M; NaN for a non-rotating metric (a
        single photon sphere).
    """
    metric = _as_rotating(metric)
    require_separable(metric)
    return metric.evaluate(photon_region_core, params, inclination, n_scan=n_scan)


@dataclass(frozen=True)
class ShadowContour:
    """Boundary of a black hole shadow in celestial coordinates.

    Attributes
    ----------
    alpha, beta : numpy.ndarray
        Closed curve (the first point is not repeated). Observer at infinity:
        Bardeen's celestial coordinates in units of M, ``alpha``
        perpendicular and ``beta`` parallel to the projected spin axis.
        Finite distance: see :func:`shadow_contour`.
    r_p : numpy.ndarray
        Radius of the spherical photon orbit behind each point (a constant
        for a non-rotating metric).
    inclination : float
        Observer inclination in radians.
    r_obs : float or None
        Observer radius; ``None`` for an observer at infinity.
    """

    alpha: np.ndarray
    beta: np.ndarray
    r_p: np.ndarray
    inclination: float
    r_obs: float | None


def _check_observer(metric, r_obs, params, out, what):
    if r_obs is None:
        if not metric.is_asymptotically_flat(**params):
            raise NotAsymptoticallyFlatError(
                f"Metric '{metric.name}' is not asymptotically flat for these parameters, so "
                f"the {what} seen 'from infinity' is not defined. Pass r_obs=<radius of the "
                "observer>."
            )
    if np.all(np.isnan(np.asarray(out))):
        where = "at infinity" if r_obs is None else f"at r_obs = {r_obs}"
        raise ValueError(
            f"{what}: no shadow could be computed for '{metric.name}' with the observer "
            f"{where}. Either there is no event horizon / photon region for these parameters "
            "(check blackpy.geometry.horizons and blackpy.light.photon_region), or the "
            "observer is not outside the photon region."
        )


def shadow_contour(
    metric, inclination, r_obs=None, *, n: int = 256, n_scan: int = 256, **params
) -> ShadowContour:
    r"""Shadow contour of a rotating black hole (separable metrics, scalar parameters).

    Parameters
    ----------
    metric : StationaryAxisymmetric or StaticSpherical
        A static metric gives a circle.
    inclination : float
        Polar angle :math:`i` of the observer in radians (``pi/2`` is
        edge-on). Clamped to ``[1e-4, pi - 1e-4]``.
    r_obs : float, optional
        ``None`` (default): observer at infinity, Bardeen's coordinates
        :math:`\alpha = -\xi/\sin i`, :math:`\beta = \pm\sqrt{\Theta(i)}`.
        Finite: a zero-angular-momentum observer (ZAMO) at
        :math:`(r_O, i)`. With :math:`n_{\hat\phi}, n_{\hat\theta}` the
        direction cosines of the photon in the ZAMO frame and
        :math:`R_O = \sqrt{g_{\theta\theta}(r_O, i)}`, the coordinates are
        :math:`\alpha = -R_O n_{\hat\phi}`, :math:`\beta = R_O n_{\hat\theta}`.
        They reduce to Bardeen's as :math:`r_O \to \infty` and, for a static
        metric, to the radius :math:`\sqrt{h(r_O)}\sin\alpha_{\rm sh}` of
        :func:`blackpy.light.shadow_radius`. The observer must be outside
        the photon region.
    n : int
        Number of points on each half of the contour.
    **params
        Scalar metric parameters.

    Returns
    -------
    ShadowContour

    Raises
    ------
    NotSeparableError
        If the null geodesics do not separate (ray tracing is out of scope;
        see Gradus.jl).
    NotAsymptoticallyFlatError
        If ``r_obs`` is None and the metric is not asymptotically flat.
    """
    metric = _as_rotating(metric)
    require_separable(metric)
    finite = r_obs is not None
    alpha, beta, r_p = metric.evaluate(
        contour_core,
        params,
        inclination,
        r_obs if finite else np.inf,
        n=n,
        n_scan=n_scan,
        finite=finite,
    )
    alpha, beta, r_p = np.asarray(alpha), np.asarray(beta), np.asarray(r_p)
    if alpha.ndim != 1:
        raise ValueError(
            "shadow_contour() needs scalar parameters and inclination; use shadow_observables() "
            "for arrays."
        )
    _check_observer(metric, r_obs, params, alpha, "shadow_contour")
    return ShadowContour(
        alpha, beta, r_p, float(inclination), None if r_obs is None else float(r_obs)
    )


def shadow_observables(
    metric, inclination, r_obs=None, *, n: int = 256, n_scan: int = 256, **params
) -> ShadowObservables:
    r"""Size and shape of the shadow (vectorised over inclination and parameters).

    Definitions, with :math:`\ell(\varphi)` the distance of the contour from
    its geometric centre :math:`(\alpha_G, 0)`,
    :math:`\alpha_G = \int\alpha\,dA / \int dA`:

    * ``area_radius``: :math:`R_A = \sqrt{A/\pi}`, the radius of the circle
      with the area of the shadow;
    * ``mean_radius``: :math:`\langle\ell\rangle =
      \frac{1}{2\pi}\oint \ell\,d\varphi`;
    * ``delta_c``: the deviation from circularity of Bambi, Freese, Vagnozzi
      & Visinelli (2019), Phys. Rev. D 100, 044057, Eqs. (4)-(5),

      .. math::

          \Delta C = \frac{1}{\bar R}\sqrt{\frac{1}{2\pi}\oint
                     (\ell - \bar R)^2\,d\varphi}, \qquad
          \bar R^2 = \frac{1}{2\pi}\oint \ell^2\,d\varphi ,

      which those authors introduced to compare with the EHT statement that
      the M87* image deviates from circularity by less than 10%. Because
      :math:`\frac12\oint\ell^2 d\varphi` is the enclosed area,
      :math:`\bar R = R_A` exactly, and
      :math:`\Delta C = \sqrt{2(1 - \langle\ell\rangle/R_A)}`;
    * ``centroid``: :math:`\alpha_G`; ``area``; ``alpha_min``,
      ``alpha_max`` (horizontal extent); ``beta_max`` (half the vertical
      extent).

    The integrals use the midpoint rule in the parameter of the contour,
    which converges exponentially for this smooth closed curve.

    Parameters
    ----------
    metric, inclination, r_obs, n
        As in :func:`shadow_contour`; ``inclination``, ``r_obs`` and the
        parameters may be arrays.
    **params
        Metric parameters.

    Returns
    -------
    ShadowObservables
        Lengths in units of M (for a finite observer: in the screen
        coordinates of :func:`shadow_contour`). NaN where no shadow exists.
        ``mean_radius`` and ``delta_c`` are NaN if the contour is not
        star-shaped about its centre.
    """
    metric = _as_rotating(metric)
    require_separable(metric)
    finite = r_obs is not None
    out = metric.evaluate(
        observables_core,
        params,
        inclination,
        r_obs if finite else np.inf,
        n=n,
        n_scan=n_scan,
        finite=finite,
    )
    _check_observer(metric, r_obs, params, out.area_radius, "shadow_observables")
    return out
