"""Run the Python snippets of a Markdown page (used by ``tests/test_docs.py``,
``scripts/update_doc_outputs.py`` and ``docs/make_figures.py``).

Conventions in the documentation:

* ```` ```python ```` blocks are executed in order, in one namespace per file.
* A block that is not meant to run is ```` ```python-skip ```` or ```` ```text ````.
* A ```` ```text title="Output" ```` block directly after a Python block is the
  output of that block: it must equal what the block prints (``print`` only;
  trailing spaces ignored).
* A ```` ```text title="Output (sampler)" ```` block is compared with a tolerance
  on numbers (relative or absolute difference up to 0.05), because a Monte Carlo
  chain can differ in its last digits between machines; the text must match.
* A ```` ```text title="Output (registry data)" ```` block is the same, but its
  numbers depend on values of the data registry, which change with a new
  ``dataset_version`` whenever a check finds an error. Tests do not depend on them
  (``CLAUDE.md``), so this output is regenerated by ``scripts/update_doc_outputs.py``
  but not compared.
* A line ``# warns: CategoryA, CategoryB`` in a block lists the BlackPy warnings the
  block emits; the set must match exactly. A block without it must emit none.
  Warnings that are not :class:`blackpy.errors.BlackPyWarning` (for example from
  dependencies) are ignored. One exception: ``UnverifiedDataWarning`` depends on the
  ``verified_by_human`` flags that the owner sets by hand in the registry, so a block
  that documents it may stop emitting it once its datasets are verified; a block that
  emits it must still document it.
"""

from __future__ import annotations

import contextlib
import io
import re
import warnings
from dataclasses import dataclass, field
from pathlib import Path

FENCE = re.compile(r"^```(?P<info>[^\n]*)\n(?P<body>.*?)^```[ \t]*$", re.MULTILINE | re.DOTALL)
OUTPUT_INFO = 'text title="Output"'
REGISTRY_OUTPUT_INFO = 'text title="Output (registry data)"'
SAMPLER_OUTPUT_INFO = 'text title="Output (sampler)"'
NUMBER = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")
SAMPLER_TOLERANCE = 0.05
# Warnings that disappear when the owner verifies registry files (see the module docstring).
DATA_DEPENDENT_WARNINGS = {"UnverifiedDataWarning"}


@dataclass
class Snippet:
    code: str
    line: int
    output: str | None = None
    output_span: tuple[int, int] | None = None
    compare: bool = True
    tolerant: bool = False
    warns: set[str] = field(default_factory=set)


def parse(text: str) -> list[Snippet]:
    """Python snippets of a Markdown text, each with its expected output block."""
    snippets: list[Snippet] = []
    matches = list(FENCE.finditer(text))
    for k, m in enumerate(matches):
        info = m.group("info").strip()
        if info != "python":
            continue
        code = m.group("body")
        warns = set()
        for line in code.splitlines():
            found = re.match(r"\s*# warns:\s*(.*)$", line)
            if found:
                warns |= {w.strip() for w in found.group(1).split(",") if w.strip()}
        snippet = Snippet(code, text.count("\n", 0, m.start()) + 1, warns=warns)
        if k + 1 < len(matches):
            nxt = matches[k + 1]
            between = text[m.end() : nxt.start()]
            info = nxt.group("info").strip()
            if (
                info in (OUTPUT_INFO, REGISTRY_OUTPUT_INFO, SAMPLER_OUTPUT_INFO)
                and not between.strip()
            ):
                snippet.output = nxt.group("body")
                snippet.output_span = (nxt.start("body"), nxt.end("body"))
                snippet.compare = info != REGISTRY_OUTPUT_INFO
                snippet.tolerant = info == SAMPLER_OUTPUT_INFO
        snippets.append(snippet)
    return snippets


def _normalise(text: str) -> str:
    return "\n".join(line.rstrip() for line in text.strip("\n").splitlines())


def _same_with_tolerance(printed: str, expected: str) -> bool:
    """Equal text, numbers equal within SAMPLER_TOLERANCE (relative or absolute)."""
    if NUMBER.sub("#", printed) != NUMBER.sub("#", expected):
        return False
    for a, b in zip(NUMBER.findall(printed), NUMBER.findall(expected), strict=True):
        x, y = float(a), float(b)
        if abs(x - y) > SAMPLER_TOLERANCE * max(1.0, abs(y)):
            return False
    return True


@dataclass
class Result:
    snippet: Snippet
    printed: str
    warned: set[str]
    error: BaseException | None = None


def run(snippets: list[Snippet], namespace: dict | None = None, name: str = "<doc>"):
    """Execute snippets in order; yield one :class:`Result` per snippet."""
    from blackpy.errors import BlackPyWarning

    namespace = {"__name__": "__docs__"} if namespace is None else namespace
    for snippet in snippets:
        buffer = io.StringIO()
        error = None
        with warnings.catch_warnings(record=True) as caught, contextlib.redirect_stdout(buffer):
            warnings.simplefilter("always")
            try:
                exec(compile(snippet.code, f"{name}:{snippet.line}", "exec"), namespace)
            except BaseException as exc:  # reported by the caller
                error = exc
        warned = {w.category.__name__ for w in caught if issubclass(w.category, BlackPyWarning)}
        yield Result(snippet, buffer.getvalue(), warned, error)


def check(result: Result) -> list[str]:
    """Problems of one executed snippet (empty if it behaves as documented)."""
    where = f"line {result.snippet.line}"
    problems = []
    if result.error is not None:
        problems.append(f"{where}: raised {type(result.error).__name__}: {result.error}")
        return problems
    optional = DATA_DEPENDENT_WARNINGS
    documented = result.snippet.warns
    same_warnings = result.warned - optional == documented - optional and (
        result.warned & optional <= documented
    )
    if not same_warnings:
        problems.append(
            f"{where}: emits {sorted(result.warned)}, documented: {sorted(result.snippet.warns)}"
        )
    snippet = result.snippet
    printed, expected = _normalise(result.printed), _normalise(snippet.output or "")
    same = _same_with_tolerance(printed, expected) if snippet.tolerant else printed == expected
    if snippet.compare and snippet.output is not None and not same:
        problems.append(
            f"{where}: printed\n{result.printed}\n--- but the guide shows ---\n"
            f"{result.snippet.output}"
        )
    return problems


def update_outputs(path: Path) -> int:
    """Rewrite the output blocks of a page with what its snippets print now."""
    text = path.read_text(encoding="utf-8")
    snippets = parse(text)
    replacements = []
    for result in run(snippets, name=path.name):
        if result.error is not None:
            raise RuntimeError(f"{path}:{result.snippet.line}") from result.error
        if result.snippet.output_span is not None:
            replacements.append((result.snippet.output_span, _normalise(result.printed) + "\n"))
    for (start, end), new in sorted(replacements, reverse=True):
        text = text[:start] + new + text[end:]
    path.write_text(text, encoding="utf-8")
    return len(replacements)
